fn swift_type(shape: &'static Shape) -> Result<String, SwiftCodegenError> {
    if is_bytes(shape) {
        return Ok("[UInt8]".to_owned());
    }
    match classify_shape(shape) {
        ShapeKind::Scalar(ScalarType::Bool) => Ok("Bool".to_owned()),
        ShapeKind::Scalar(ScalarType::Unit) => Ok("Void".to_owned()),
        ShapeKind::Scalar(ScalarType::U8) => Ok("UInt8".to_owned()),
        ShapeKind::Scalar(ScalarType::U16) => Ok("UInt16".to_owned()),
        ShapeKind::Scalar(ScalarType::U32) => Ok("UInt32".to_owned()),
        ShapeKind::Scalar(ScalarType::U64) => Ok("UInt64".to_owned()),
        ShapeKind::Scalar(ScalarType::I32) => Ok("Int32".to_owned()),
        ShapeKind::Scalar(ScalarType::I64) => Ok("Int64".to_owned()),
        ShapeKind::Scalar(ScalarType::F64) => Ok("Double".to_owned()),
        ShapeKind::Scalar(ScalarType::Str | ScalarType::String | ScalarType::CowStr) => {
            Ok("String".to_owned())
        }
        ShapeKind::List { element } | ShapeKind::Slice { element } => {
            Ok(format!("[{}]", swift_type(element)?))
        }
        ShapeKind::Tuple { .. } | ShapeKind::TupleStruct { .. } => tuple_carrier_type_name(shape),
        ShapeKind::Option { inner } => Ok(format!("{}?", swift_type(inner)?)),
        ShapeKind::Struct(StructInfo {
            name: Some(name), ..
        })
        | ShapeKind::Enum(EnumInfo {
            name: Some(name), ..
        }) => Ok(name.to_upper_camel_case()),
        ShapeKind::Tx { .. } | ShapeKind::Rx { .. } => Ok("VoxSwiftChannel".to_owned()),
        ShapeKind::Result { .. } => result_carrier_type_name(shape),
        _ => Err(unsupported(
            shape,
            "no Swift type spelling for this shape yet",
        )),
    }
}

fn swift_shape_type(shape: &'static Shape) -> Result<String, SwiftCodegenError> {
    match classify_shape(shape) {
        ShapeKind::Struct(StructInfo {
            name: Some(name), ..
        })
        | ShapeKind::Enum(EnumInfo {
            name: Some(name), ..
        }) => Ok(name.to_upper_camel_case()),
        _ => swift_type(shape),
    }
}

